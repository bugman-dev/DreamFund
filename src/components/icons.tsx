export function AppIcon({
  name,
  size = 22,
  color,
  strokeWidth = 2,
}: {
  name: string;
  size?: number;
  color: string;
  strokeWidth?: number;
}) {
  const Icon = ICONS[name as IconName] ?? Circle;
  return <Icon size={size} color={color} strokeWidth={strokeWidth} />;
}
